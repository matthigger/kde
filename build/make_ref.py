"""Write test/ref.js: sklearn answers for js/kde.js to match.

Usage:
    ~/venv_ds4400/bin/python -I build/make_ref.py

Density cases: sklearn KernelDensity.score_samples (ln p̂) for every kernel
at two bandwidths on seeded samples and probes, plus a tiny-bandwidth
Gaussian case far from the samples (checks the log-space sums). CV cases:
for fixed fold labels, the mean over folds of each fold's mean held-out
score_samples, on a bandwidth grid (Gaussian, and Epanechnikov, where a
held-out sample out of reach of every bump scores -inf). Scott's rule
sigma n^(-1/5) with the n - 1 standard deviation (Scott 1992).
"""
import json
import pathlib

import numpy as np
from sklearn.neighbors import KernelDensity

OUT = pathlib.Path(__file__).resolve().parent.parent / "test" / "ref.js"
KERNELS = ["gaussian", "tophat", "epanechnikov", "linear", "cosine",
           "exponential"]


def ln_kde(x, probe, h: float, kernel: str) -> list:
    """sklearn ln p̂ at probe, with JSON-safe -inf (as None)."""
    k = KernelDensity(kernel=kernel, bandwidth=h).fit(np.asarray(x)[:, None])
    s = k.score_samples(np.asarray(probe)[:, None])
    return [None if np.isneginf(v) else float(v) for v in s]


def density_cases() -> list:
    """Every kernel at two bandwidths, plus one tiny-h Gaussian case."""
    rng = np.random.default_rng(0)
    x = np.r_[rng.normal(0, 1, 25), rng.normal(4, .5, 15)]
    probe = np.r_[rng.uniform(-3, 7, 30), x[:5]]
    out = [{"x": x.tolist(), "probe": probe.tolist(), "h": h, "kern": k,
            "ln": ln_kde(x, probe, h, k)}
           for k in KERNELS for h in (.35, 1.2)]
    far = [10., 15., -9.]
    out.append({"x": x.tolist(), "probe": far, "h": .01, "kern": "gaussian",
                "ln": ln_kde(x, far, .01, "gaussian")})
    return out


def cv_case(kernel: str, seed: int) -> dict:
    """Mean over 5 folds of the mean held-out ln p̂, on an h grid."""
    rng = np.random.default_rng(seed)
    n, k = 60, 5
    x = np.r_[rng.normal(0, 1, n // 2), rng.normal(5, 1, n - n // 2)]
    folds = rng.permutation(np.arange(n) % k)
    hs = np.geomspace(.02, 3, 9)
    mean = []
    for h in hs:
        tot = 0.
        for j in range(k):
            s = ln_kde(x[folds != j], x[folds == j], h, kernel)
            tot += (-np.inf if None in s else np.mean(s)) / k
        mean.append(None if np.isneginf(tot) else float(tot))
    return {"x": x.tolist(), "folds": folds.tolist(), "k": k,
            "hs": hs.tolist(), "kern": kernel, "mean": mean,
            "scott": float(x.std(ddof=1) * n ** -.2)}


def main() -> None:
    ref = {"density": density_cases(),
           "cv": [cv_case("gaussian", 1), cv_case("epanechnikov", 2)]}
    OUT.write_text("// sklearn answers on fixed samples: generated by"
                   " build/make_ref.py.\nconst REF = " +
                   json.dumps(ref) + ";\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
